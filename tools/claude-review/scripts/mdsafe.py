#!/usr/bin/env python3
"""render.py と post_inline.py が共有する Markdown 安全化ヘルパー。

title / source / reason / detail / evidence / note / replacement / why /
summary / file はすべて Claude の出力由来で、その元は公開 PR に誰でも書ける
レビューコメント。github-actions[bot] として public リポジトリに投稿される
ため、コードフェンスの外に置くものは必ずここを通す。

以前は render.py と post_inline.py がこのロジックをバイト同一のまま複製
していた。3 行程度のうちは許容できたが、行頭の構造記号を無害化する
セキュリティ修正を一箇所にまとめる必要が出たため、ここに集約する。
"""
from __future__ import annotations

import re

# 行頭で CommonMark のブロックを開きうる記号。
#   `#`  ATX 見出し
#   `>`  引用
#   `-` `+` `*`  箇条書き・区切り線
#   `` ` `` `~`  コードフェンス
#   `=`  setext 見出しの下線
#   `_`  区切り線
# 0〜3 個の半角スペースまではインデントとして許容されるため、その後ろの
# 最初の 1 文字だけを見る。
_LEADING_STRUCT = re.compile(r"^( {0,3})([#>\-+*`~=_])")

# 番号付きリストは記号 1 文字ではなく「数字列 + `.`/`)`」がマーカーになる。
# CommonMark はバックスラッシュで数字自体をエスケープしても効かない
# （`\1` はそのまま `\1` と解釈される）ため、区切り文字（`.`/`)`）の
# 直前にバックスラッシュを置いて区切り文字自体を無害化する。
_LEADING_ORDERED = re.compile(r"^( {0,3})(\d+)([.)])")

# @mention 無害化用のゼロ幅スペース(U+200B)。「@」の直後に挿入し、
# 見た目を変えずに「@username」としての文字の連続性だけを断つ。
_ZWSP = "​"


def esc(s) -> str:
    """コードフェンスの外に置く外部由来文字列をエスケープする。

    - `<`/`>` を実体参照に変換し、`<details>` などの HTML タグとしての解釈を
      防ぐ（`&` は変換しない — Claude が既に `&lt;` 等を出力していた場合の
      二重エスケープになるため）。
    - 改行（`\\r\\n`/`\\n`/`\\r`）を半角スペース 1 つに畳み込む。CommonMark は
      見出し・箇条書き・引用・区切り線の前に空行を要求しないため、改行を
      残すと偽の見出しや箇条書き、区切り線をトップレベルの文書構造に
      注入できてしまう（表示崩れではなく構造の偽装）。ここで扱う文字列は
      いずれも 1〜3 文の短い要約で、意図的な改行が失われても情報は落ちない。
    - 上記 2 つの処理のあと、結果の**先頭**が（0〜3 個の空白を挟んで）
      ブロックを開く記号だった場合、その記号の直前にバックスラッシュを
      挿入して無害化する。呼び出し側の多くはこの戻り値をそのまま独立した
      段落・見出し・箇条書きの 1 行として出力するため、改行を畳んだだけでは
      「行の途中」にはならず、先頭に来た記号がそれ単独でブロックを開いて
      しまう（例: `"```\\nrest hidden"` は畳み込み後 `"``` rest hidden"` と
      なり未閉のコードフェンスを開く。`"## 見出し"` はそのままトップレベル
      見出しになる）。CommonMark はバックスラッシュで ASCII の記号を
      エスケープできるので、`\\#` は文字どおりの `#` として表示される。
      ここでエスケープするのは行頭の 1 箇所だけであり、文中の書式には
      触れない。
    - `@` の直後にゼロ幅スペース(U+200B)を挿入し、`@ユーザー名` としての
      文字の連続性を断つ。GitHub の @mention 通知・リンク化は
      CommonMark/GFM の仕様には無く、Markdown を HTML にレンダリングした
      **後**にレンダリング結果のテキストノードを正規表現
      `@[a-z0-9][a-z0-9-]*` で走査する別処理（html-pipeline の
      MentionFilter、`<code>`/`<pre>`/`<a>` の中は除外）。CommonMark の
      バックスラッシュエスケープは Markdown 構文としての解釈を止める
      だけで、レンダリング結果には「エスケープされていた」という情報が
      残らない（`\\@x` も `@x` もレンダリング後は同じ「@x」というテキスト
      ノードになる）ため、行頭記号の無害化（本関数の前段、CommonMark 自身
      によるレンダリング**前**の生テキストのブロック解析）とは異なり、
      メンション化には効かない。ゼロ幅スペースは表示に影響を与えないまま
      隣接を断つため、この別処理にも、生のコメント本文を素朴な部分文字列
      一致で走査する外部 bot（例:「@coderabbitai full review」という
      コマンド文字列そのもの）にも同時に効く。
      対象は Claude 出力由来の title/source/reason/detail/... で、
      `render.py` 自身が組み立てるテンプレート文字列中の `@` は別途
      テンプレート側で削っている（本関数ではテンプレートの文字までは
      触れない）。
    - コードフェンスの中身（`replacement`/`evidence`）にはこの関数を通さない
      ——改行はコードの一部であり、保持する。フェンス自体は `fence()` で
      内容に応じた長さを確保することで封じ込める。`@` もここでは
      加工しない：コードとして扱われ、GitHub の MentionFilter も
      `<code>`/`<pre>` の中はメンション化の対象外にしている。
    """
    s = str(s)
    s = s.replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("@", "@" + _ZWSP)
    s = re.sub(r"\r\n|\r|\n", " ", s)

    m = _LEADING_ORDERED.match(s)
    if m:
        cut = m.end(2)                 # 数字列の直後、区切り文字の直前
        return s[:cut] + "\\" + s[cut:]

    m = _LEADING_STRUCT.match(s)
    if m:
        cut = m.end(1)                 # 先頭の空白の直後、記号の直前
        return s[:cut] + "\\" + s[cut:]

    return s


def cell(s) -> str:
    """Markdown 表のセルに置く文字列を作る。

    `esc()` に加えて、`\\`（バックスラッシュ）と `|` をエスケープする。
    GFM の行分割は `|` の直前に連続するバックスラッシュの個数の偶奇で
    「エスケープ済みか」を判定する（奇数個なら区切りではない）。そのため
    バックスラッシュを先に、パイプを後にエスケープする必要があり、ここでは
    1 回の正規表現でどちらの文字も置換することで順序を保証する
    （`s.replace("|", "\\|")` を先に呼ぶと、入力に既にあるバックスラッシュを
    2 本ペアと誤認させ、パイプが区切りとして復活する回帰を生む）。
    """
    return re.sub(r"([\\|])", r"\\\1", esc(s))


def fence(content: str) -> str:
    """内容を安全に囲めるコードフェンスを返す。

    中身に含まれるバッククォートの連続の最大長 + 1（最小 3）の長さにする
    （CommonMark の標準的なやり方）。内容そのものはエスケープしない —
    コードとして読ませるのが目的で、フェンス長で囲めば十分なため。

    post_inline.py で使う場合、フェンスの本数を増やしても直後に続く
    info string（`suggestion`）自体は変えないこと。GitHub が one-click
    apply の対象として解釈するのは info string がちょうど "suggestion"
    の場合のみなので、ここを崩してはならない。
    """
    runs = re.findall(r"`+", content)
    longest = max((len(r) for r in runs), default=0)
    return "`" * max(3, longest + 1)
